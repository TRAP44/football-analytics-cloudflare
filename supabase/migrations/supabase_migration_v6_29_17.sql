-- MatchRadar v6.29.17 / invite rewards: +1 bonus full analysis for both sides
-- A referred user (attributed on /start via the existing referral code, see
-- growth_events 'referred_first_open') who is new (registered at most an hour
-- before the attribution) earns one bonus analysis after the first successful
-- analysis; the referrer earns one too, at most p_monthly_cap per 30 days.
-- A bonus is spent only after the daily free quota is exhausted and is returned
-- if the analysis fails. Rewards are not purchases: no stars, no entitlements.
-- Service only. No browser role has table access or function EXECUTE.
--
-- Rollout order: apply this migration first (the production deploy gate
-- requires it), then deploy the Worker. Legacy v1 fingerprint stays frozen:
-- backend_schema_fingerprint() excludes the new table and functions.

create table if not exists public.referral_rewards (
  id bigint generated by default as identity primary key,
  telegram_id bigint not null check (telegram_id > 0),
  referred_telegram_id bigint not null check (referred_telegram_id > 0),
  role text not null check (role in ('referrer','referred')),
  status text not null default 'available' check (status in ('available','used')),
  operation_id uuid,
  granted_at timestamptz not null default now(),
  used_at timestamptz,
  unique (referred_telegram_id, role),
  check ((status = 'used') = (used_at is not null))
);
create index if not exists referral_rewards_owner_status_idx
  on public.referral_rewards(telegram_id, status, granted_at);
alter table public.referral_rewards enable row level security;
revoke all on table public.referral_rewards from public, anon, authenticated, service_role;
grant select, insert, update, delete on table public.referral_rewards to service_role;

create or replace function public.grant_referral_rewards(
  p_referred_telegram_id bigint,
  p_monthly_cap integer default 10
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_catalog, pg_temp
as $$
declare
  v_attribution public.growth_events%rowtype;
  v_code text;
  v_referrer bigint;
  v_user_created timestamptz;
  v_recent integer;
  v_rows integer;
  v_referred_granted boolean := false;
  v_referrer_granted boolean := false;
  v_cap integer := least(greatest(coalesce(p_monthly_cap, 10), 0), 100);
begin
  if p_referred_telegram_id is null or p_referred_telegram_id <= 0 then
    return jsonb_build_object('granted', false, 'reason', 'invalid_input');
  end if;

  select *
  into v_attribution
  from public.growth_events
  where event_key = 'referral_attribution:' || p_referred_telegram_id
    and event_name = 'referred_first_open'
    and telegram_id = p_referred_telegram_id
  order by created_at asc, id asc
  limit 1;
  if not found then
    return jsonb_build_object('granted', false, 'reason', 'not_referred');
  end if;

  v_code := lower(coalesce(v_attribution.metadata->>'referral_code', ''));
  if v_code !~ '^[a-f0-9]{16}$' then
    return jsonb_build_object('granted', false, 'reason', 'invalid_code');
  end if;

  select telegram_id
  into v_referrer
  from public.growth_events
  where event_key = 'referral_code:' || v_code
    and event_name = 'referral_code_created'
  order by created_at asc, id asc
  limit 1;
  if v_referrer is null or v_referrer <= 0 then
    return jsonb_build_object('granted', false, 'reason', 'unknown_referrer');
  end if;
  if v_referrer = p_referred_telegram_id then
    return jsonb_build_object('granted', false, 'reason', 'self_referral');
  end if;

  select created_at
  into v_user_created
  from public.users
  where telegram_id = p_referred_telegram_id;
  if v_user_created is null or v_user_created < v_attribution.created_at - interval '1 hour' then
    return jsonb_build_object('granted', false, 'reason', 'not_new_user');
  end if;

  -- One decision per referred user; the referrer cap is counted under a lock.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext('matchradar:referral-reward'),
    pg_catalog.hashtext(v_referrer::text)
  );

  insert into public.referral_rewards (telegram_id, referred_telegram_id, role)
  values (p_referred_telegram_id, p_referred_telegram_id, 'referred')
  on conflict (referred_telegram_id, role) do nothing;
  get diagnostics v_rows = row_count;
  v_referred_granted := v_rows > 0;

  if not v_referred_granted then
    return jsonb_build_object('granted', false, 'reason', 'already_granted', 'referrerId', v_referrer);
  end if;

  select count(*)
  into v_recent
  from public.referral_rewards
  where telegram_id = v_referrer
    and role = 'referrer'
    and granted_at > now() - interval '30 days';

  if v_recent < v_cap then
    insert into public.referral_rewards (telegram_id, referred_telegram_id, role)
    values (v_referrer, p_referred_telegram_id, 'referrer')
    on conflict (referred_telegram_id, role) do nothing;
    get diagnostics v_rows = row_count;
    v_referrer_granted := v_rows > 0;
  end if;

  return jsonb_build_object(
    'granted', true,
    'referredGranted', v_referred_granted,
    'referrerGranted', v_referrer_granted,
    'referrerId', v_referrer,
    'reason', case when v_referrer_granted then 'granted' else 'referrer_cap_reached' end
  );
end;
$$;

create or replace function public.reserve_referral_bonus(
  p_telegram_id bigint,
  p_operation_id uuid
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_catalog, pg_temp
as $$
declare
  v_id bigint;
  v_left integer;
begin
  if p_telegram_id is null or p_telegram_id <= 0 or p_operation_id is null then
    return jsonb_build_object('allowed', false, 'reason', 'invalid_input');
  end if;

  select id
  into v_id
  from public.referral_rewards
  where telegram_id = p_telegram_id
    and status = 'available'
  order by granted_at asc, id asc
  limit 1
  for update skip locked;
  if v_id is null then
    return jsonb_build_object('allowed', false, 'reason', 'no_bonus');
  end if;

  update public.referral_rewards
  set status = 'used', used_at = now(), operation_id = p_operation_id
  where id = v_id;

  select count(*)
  into v_left
  from public.referral_rewards
  where telegram_id = p_telegram_id
    and status = 'available';

  return jsonb_build_object('allowed', true, 'rewardId', v_id, 'remaining', v_left);
end;
$$;

create or replace function public.refund_referral_bonus(
  p_telegram_id bigint,
  p_reward_id bigint,
  p_operation_id uuid
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_catalog, pg_temp
as $$
declare
  v_rows integer;
begin
  if p_telegram_id is null or p_telegram_id <= 0
     or p_reward_id is null or p_reward_id <= 0
     or p_operation_id is null then
    return jsonb_build_object('refunded', false, 'reason', 'invalid_input');
  end if;

  update public.referral_rewards
  set status = 'available', used_at = null, operation_id = null
  where id = p_reward_id
    and telegram_id = p_telegram_id
    and status = 'used'
    and operation_id = p_operation_id;
  get diagnostics v_rows = row_count;

  return jsonb_build_object('refunded', v_rows > 0, 'reason', case when v_rows > 0 then 'refunded' else 'not_found' end);
end;
$$;

revoke all on function public.grant_referral_rewards(bigint, integer) from public, anon, authenticated;
grant execute on function public.grant_referral_rewards(bigint, integer) to service_role;
revoke all on function public.reserve_referral_bonus(bigint, uuid) from public, anon, authenticated;
grant execute on function public.reserve_referral_bonus(bigint, uuid) to service_role;
revoke all on function public.refund_referral_bonus(bigint, bigint, uuid) from public, anon, authenticated;
grant execute on function public.refund_referral_bonus(bigint, bigint, uuid) to service_role;

-- Freeze the historical v1 fingerprint: the new table and functions are excluded.
create or replace function public.backend_schema_fingerprint()
returns jsonb
language sql
stable
security invoker
set search_path = public, pg_catalog, pg_temp
as $$
with parts as (
  select
    'C|' || c.table_name || '|' || c.ordinal_position || '|' || c.column_name || '|' ||
    c.data_type || '|' || coalesce(c.udt_name,'') || '|' || c.is_nullable || '|' ||
    coalesce(c.column_default,'') as part
  from information_schema.columns c
  where c.table_schema = 'public'
    and c.table_name not in (
      'provider_incident_alert_deliveries',
      'analysis_timeline_snapshots',
      'favorite_players',
      'smart_notification_deliveries',
      'user_entitlements',
      'scheduled_job_leases',
      'provider_slo_buckets',
      'sensitive_mutation_idempotency',
      'match_picks',
      'referral_rewards'
    )
    and not (
      (c.table_name = 'analysis_cache' and c.column_name in ('provider','source_updated_at','freshness_status','updated_at'))
      or (c.table_name = 'odds_snapshots' and c.column_name in ('provider','bookmaker_count','source_updated_at'))
      or (c.table_name = 'model_predictions' and c.column_name in ('data_provenance','model_inputs_version'))
      or (c.table_name = 'ops_events' and c.column_name in ('transition_key','occurrence_count','last_occurred_at'))
      or (c.table_name = 'user_preferences' and c.column_name = 'notification_preferences')
      or (c.table_name = 'runtime_controls' and c.column_name = 'ai_enabled')
      or (c.table_name = 'match_reminders' and c.column_name in (
        'lineup_notified_at','lineup_claimed_at','lineup_attempts',
        'important_change_notified_at','important_change_claimed_at','important_change_attempts'
      ))
    )

  union all

  select
    'K|' || tc.table_name || '|' || tc.constraint_name || '|' || tc.constraint_type || '|' ||
    coalesce(pg_get_constraintdef(pc.oid, true),'')
  from information_schema.table_constraints tc
  join pg_constraint pc on pc.conname = tc.constraint_name
  join pg_namespace pn on pn.oid = pc.connamespace and pn.nspname = 'public'
  where tc.table_schema = 'public'
    and tc.table_name not in (
      'provider_incident_alert_deliveries',
      'analysis_timeline_snapshots',
      'favorite_players',
      'smart_notification_deliveries',
      'user_entitlements',
      'scheduled_job_leases',
      'provider_slo_buckets',
      'sensitive_mutation_idempotency',
      'match_picks',
      'referral_rewards'
    )
    and tc.constraint_name <> 'user_preferences_notification_preferences_object_check'
    and not (tc.table_name = 'ops_events' and tc.constraint_name = 'ops_events_transition_key_key')

  union all

  select 'I|' || indexname || '|' || indexdef
  from pg_indexes
  where schemaname = 'public'
    and tablename not in (
      'provider_incident_alert_deliveries',
      'analysis_timeline_snapshots',
      'favorite_players',
      'smart_notification_deliveries',
      'user_entitlements',
      'scheduled_job_leases',
      'provider_slo_buckets',
      'sensitive_mutation_idempotency',
      'match_picks',
      'referral_rewards'
    )
    and not (tablename = 'ops_events' and indexname = 'ops_events_transition_key_key')

  union all

  select
    'F|' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')|' ||
    pg_get_function_result(p.oid) || '|definer=' || p.prosecdef::text
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.proname not in (
      'save_favorite_guarded',
      'save_favorite_player_guarded',
      'save_match_reminder_guarded',
      'save_match_reminder_guarded_v2',
      'resolve_match_reminder_fixture',
      'prune_match_reminders_for_user',
      'personal_write_guard_contract',
      'claim_provider_incident_alert_delivery',
      'finalize_provider_incident_alert_delivery',
      'provider_incident_alert_delivery_contract',
      'claim_smart_notification_delivery',
      'finalize_smart_notification_delivery',
      'begin_smart_notification_delivery_send',
      'activate_pass_entitlement',
      'consume_pass_entitlement',
      'refund_pass_entitlement_usage',
      'refund_pass_entitlement',
      'backend_readiness_contract',
      'claim_scheduled_job',
      'complete_scheduled_job',
      'release_scheduled_job',
      'renew_scheduled_job',
      'record_provider_slo_observation',
      'read_provider_slo_buckets',
      'provider_slo_aggregation_contract',
      'claim_provider_incident_alert_delivery_v2',
      'begin_provider_incident_alert_delivery_send',
      'record_ops_event_occurrence',
      'claim_sensitive_mutation',
      'complete_sensitive_mutation',
      'fail_sensitive_mutation',
      'cleanup_sensitive_mutation_idempotency',
      'backend_schema_contract_v2',
      'backend_readiness_contract_v2',
      'grant_referral_rewards',
      'reserve_referral_bonus',
      'refund_referral_bonus'
    )
)
select jsonb_build_object(
  'ok', true,
  'fingerprint', md5(string_agg(part, E'\n' order by part)),
  'parts', count(*),
  'checked_at', now()
)
from parts;
$$;

revoke all on function public.backend_schema_fingerprint()
  from public, anon, authenticated;
grant execute on function public.backend_schema_fingerprint()
  to service_role;

notify pgrst, 'reload schema';
